            SELECT * INTO b FROM achats.tickets WHERE code = r.base;
            CONTINUE WHEN b.id IS NULL OR EXISTS (SELECT 1 FROM achats.tickets WHERE code = r.code);
            INSERT INTO achats.tickets (code, magasin_id, date, numero, source, total_articles, paye)
            VALUES (r.code, b.magasin_id, b.date, r.numero, b.source, 0, 0) RETURNING id INTO nouveau;
            FOR s IN SELECT * FROM lignes_recus WHERE code = r.code LOOP
                UPDATE achats.lignes SET ticket_id = nouveau WHERE id IN (
                    SELECT l.id FROM achats.lignes l JOIN achats.produits p ON p.id = l.produit_id
                    WHERE l.ticket_id = b.id AND p.libelle = s.libelle AND l.quantite = s.quantite AND l.montant = s.montant
                    ORDER BY l.id DESC LIMIT s.n);
                GET DIAGNOSTICS n = ROW_COUNT;
                IF n <> s.n THEN RAISE EXCEPTION 'ligne introuvable : %', s.libelle; END IF;
            END LOOP;
            UPDATE achats.tickets t SET total_articles = x.montant, paye = x.montant - x.remise
            FROM (SELECT l.ticket_id, sum(l.montant) AS montant, COALESCE(sum(p.montant), 0) AS remise
                  FROM achats.lignes l LEFT JOIN achats.promos p ON p.ligne_id = l.id
                  WHERE l.ticket_id IN (b.id, nouveau) GROUP BY l.ticket_id) x
            WHERE t.id = x.ticket_id;
        EXCEPTION WHEN raise_exception THEN
            RAISE NOTICE 'Reçu % laissé dans %: %', r.code, r.base, SQLERRM;
        END;
    END LOOP;

    UPDATE achats.tickets t SET numero = x.numero FROM recus x WHERE t.code = x.code AND t.numero IS NULL;
END $$;
